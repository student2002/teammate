// daemon_persona_test.go covers the persona key (memory identity) on agent
// instances: web creation with an explicit key, auto-generation when blank,
// format validation, delivery through desired_agents, and exposure on the
// agent DTO.
package handler_test

import (
	"encoding/json"
	"net/http"
	"regexp"
	"testing"
)

var personaGeneratedPattern = regexp.MustCompile(`^persona-[0-9a-f]{8}$`)

// createDaemonAgent posts a daemon-group instance and returns (id, personaKey, status).
// Git identity is required at creation; bodies without it get a default.
func createDaemonAgent(t *testing.T, client *http.Client, baseURL, wsID, daemonID, memberToken string, body map[string]string) (string, string, int, []byte) {
	t.Helper()
	if _, ok := body["git_name"]; !ok {
		body["git_name"] = "Tester"
	}
	if _, ok := body["git_email"]; !ok {
		body["git_email"] = "tester@teammate.local"
	}
	_, status, respBody := doRequestWithToken(t, client, http.MethodPost,
		baseURL+"/api/workspaces/"+wsID+"/daemons/"+daemonID+"/agents", memberToken, body)
	if status != http.StatusCreated {
		return "", "", status, respBody
	}
	var created struct {
		ID         string `json:"id"`
		PersonaKey string `json:"persona_key"`
	}
	if err := json.Unmarshal(respBody, &created); err != nil {
		t.Fatalf("decode created agent: %v", err)
	}
	return created.ID, created.PersonaKey, status, respBody
}

// personaInDB reads the stored persona_key of one agent row.
func personaInDB(t *testing.T, dbh *dbHandle, agentID string) string {
	t.Helper()
	var persona string
	if err := dbh.db.QueryRow(`SELECT persona_key FROM agents WHERE id = $1::uuid`, agentID).Scan(&persona); err != nil {
		t.Fatalf("query persona_key: %v", err)
	}
	return persona
}

// TestDaemonAgentPersonaAutoGenerated proves a blank persona_key on creation
// is filled with a unique generated value both in the row and on the DTO.
func TestDaemonAgentPersonaAutoGenerated(t *testing.T) {
	ts, client, dbh := setupDaemonTestServerWithDB(t)
	memberToken, wsID := registerTestUser(t, client, ts.URL)

	daemonID, tdToken := createTestDaemon(t, client, ts.URL, wsID, memberToken, "dev-box")
	registerProviders(t, client, ts.URL, tdToken)

	idA, personaA, status, respBody := createDaemonAgent(t, client, ts.URL, wsID, daemonID, memberToken,
		map[string]string{"name": "claude-01", "provider": "claude"})
	if status != http.StatusCreated {
		t.Fatalf("create agent: expected 201, got %d, body: %s", status, respBody)
	}
	if !personaGeneratedPattern.MatchString(personaA) {
		t.Fatalf("blank persona_key should be auto-generated, got %q", personaA)
	}
	if got := personaInDB(t, dbh, idA); got != personaA {
		t.Fatalf("stored persona_key %q differs from DTO %q", got, personaA)
	}

	// a second blank creation gets a different generated key (default isolation)
	_, personaB, status, respBody := createDaemonAgent(t, client, ts.URL, wsID, daemonID, memberToken,
		map[string]string{"name": "claude-02", "provider": "claude"})
	if status != http.StatusCreated {
		t.Fatalf("create second agent: expected 201, got %d, body: %s", status, respBody)
	}
	if personaA == personaB {
		t.Fatalf("two blank creations must not share a persona: %q", personaA)
	}
}

