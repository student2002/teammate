// TestDaemonAgentPersonaValidation proves illegal persona_keys are rejected
// with 400 before any row is created.
func TestDaemonAgentPersonaValidation(t *testing.T) {
	ts, client, dbh := setupDaemonTestServerWithDB(t)
	memberToken, wsID := registerTestUser(t, client, ts.URL)

	daemonID, tdToken := createTestDaemon(t, client, ts.URL, wsID, memberToken, "dev-box")
	registerProviders(t, client, ts.URL, tdToken)

	for _, bad := range []string{"x", "has space", "非法字符", "-leading", ".dot", "a b", makeLen(65)} {
		_, _, status, respBody := createDaemonAgent(t, client, ts.URL, wsID, daemonID, memberToken,
			map[string]string{"name": "claude-01", "provider": "claude", "persona_key": bad})
		if status != http.StatusBadRequest {
			t.Fatalf("persona_key %q: expected 400, got %d, body: %s", bad, status, respBody)
		}
	}

	var n int
	if err := dbh.db.QueryRow(`SELECT COUNT(*) FROM agents WHERE workspace_id = $1::uuid`, wsID).Scan(&n); err != nil {
		t.Fatalf("count agents: %v", err)
	}
	if n != 0 {
		t.Fatalf("rejected creations must not leave rows, found %d", n)
	}
}

func makeLen(n int) string {
	b := make([]byte, n)
	for i := range b {
		b[i] = 'a'
	}
	return string(b)
}

// TestDaemonAgentPersonaDelivered proves desired_agents carries each
// instance's persona_key (the cross-workspace memory identity agentd keys on).
