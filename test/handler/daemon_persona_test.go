// TestDaemonDesiredFullSetReconcile proves the declarative full-set delivery:
// desired_agents always carries every instance of the daemon (online ones
// included), and a deleted instance disappears from the next full set.
func TestDaemonDesiredFullSetReconcile(t *testing.T) {
	ts, client := setupDaemonTestServer(t)
	memberToken, wsID := registerTestUser(t, client, ts.URL)

	daemonID, tdToken := createTestDaemon(t, client, ts.URL, wsID, memberToken, "dev-box")
	registerProviders(t, client, ts.URL, tdToken)

	idA, _, status, respBody := createDaemonAgent(t, client, ts.URL, wsID, daemonID, memberToken,
		map[string]string{"name": "claude-01", "provider": "claude", "persona_key": "shared.brain-1"})
	if status != http.StatusCreated {
		t.Fatalf("create A: expected 201, got %d, body: %s", status, respBody)
	}
	idB, personaB, status, respBody := createDaemonAgent(t, client, ts.URL, wsID, daemonID, memberToken,
		map[string]string{"name": "claude-02", "provider": "claude"})
	if status != http.StatusCreated {
		t.Fatalf("create B: expected 201, got %d, body: %s", status, respBody)
	}

	register := func() map[string]struct {
		PersonaKey string `json:"persona_key"`
	} {
		t.Helper()
		code, body := daemonRequest(t, client, http.MethodPost,
			ts.URL+"/api/daemons/register", tdToken, "", registerBody())
		if code != http.StatusOK {
			t.Fatalf("register: expected 200, got %d, body: %s", code, body)
		}
		var resp struct {
			DesiredAgents []struct {
				AgentID    string `json:"agent_id"`
				PersonaKey string `json:"persona_key"`
			} `json:"desired_agents"`
		}
		if err := json.Unmarshal(body, &resp); err != nil {
			t.Fatalf("decode register response: %v", err)
		}
		out := map[string]struct {
			PersonaKey string `json:"persona_key"`
		}{}
		for _, a := range resp.DesiredAgents {
			out[a.AgentID] = struct {
				PersonaKey string `json:"persona_key"`
			}{PersonaKey: a.PersonaKey}
		}
		return out
	}

	// full set right after creation: both instances with their personas
	full := register()
	if len(full) != 2 {
		t.Fatalf("expected full set of 2, got %v", full)
	}
	if full[idA].PersonaKey != "shared.brain-1" || full[idB].PersonaKey != personaB {
		t.Fatalf("full-set personas wrong: %+v", full)
	}

	// heartbeat reports A busy (online): the full set still carries both
	code, body := daemonRequest(t, client, http.MethodPost,
		ts.URL+"/api/daemons/heartbeat", tdToken, "",
		map[string]interface{}{"agents": []map[string]interface{}{{"name": "claude-01", "busy": true}}})
	if code != http.StatusOK {
		t.Fatalf("heartbeat: expected 200, got %d, body: %s", code, body)
	}
	var hb struct {
		DesiredAgents []map[string]interface{} `json:"desired_agents"`
	}
	if err := json.Unmarshal(body, &hb); err != nil {
		t.Fatalf("decode heartbeat response: %v", err)
	}
	if len(hb.DesiredAgents) != 2 {
		t.Fatalf("full set after busy report must still carry both instances, got %v", hb.DesiredAgents)
	}

	// delete B: the next full set drops it
	_, status, respBody = doRequestWithToken(t, client, http.MethodDelete,
		ts.URL+"/api/workspaces/"+wsID+"/agents/"+idB, memberToken, nil)
	if status != http.StatusNoContent {
		t.Fatalf("delete agent: expected 204, got %d, body: %s", status, respBody)
	}
	full = register()
	if len(full) != 1 {
		t.Fatalf("expected full set of 1 after deletion, got %v", full)
	}
	if _, still := full[idB]; still {
		t.Fatal("deleted instance still in the full set")
	}
	if full[idA].PersonaKey != "shared.brain-1" {
		t.Fatalf("surviving instance persona wrong: %+v", full)
	}
}

// TestDaemonAgentPersonaOnAgentList proves the workspace agent list DTO
// exposes persona_key for the web card badge.
func TestDaemonAgentPersonaOnAgentList(t *testing.T) {
	ts, client := setupDaemonTestServer(t)
	memberToken, wsID := registerTestUser(t, client, ts.URL)

	daemonID, tdToken := createTestDaemon(t, client, ts.URL, wsID, memberToken, "dev-box")
	registerProviders(t, client, ts.URL, tdToken)

	_, persona, status, respBody := createDaemonAgent(t, client, ts.URL, wsID, daemonID, memberToken,
		map[string]string{"name": "claude-01", "provider": "claude", "persona_key": "shared.brain-1"})
	if status != http.StatusCreated {
		t.Fatalf("create agent: expected 201, got %d, body: %s", status, respBody)
	}
	if persona != "shared.brain-1" {
		t.Fatalf("explicit persona_key should round-trip, got %q", persona)
	}

	_, status, respBody = doRequestWithToken(t, client, http.MethodGet,
		ts.URL+"/api/workspaces/"+wsID+"/agents", memberToken, nil)
	if status != http.StatusOK {
		t.Fatalf("list agents: expected 200, got %d, body: %s", status, respBody)
	}
	var list []map[string]interface{}
	if err := json.Unmarshal(respBody, &list); err != nil {
		t.Fatalf("decode agent list: %v", err)
	}
	found := false
	for _, a := range list {
		if a["name"] == "claude-01" {
			found = true
			if got, _ := a["persona_key"].(string); got != "shared.brain-1" {
				t.Fatalf("agent list persona_key = %q, want %q", got, "shared.brain-1")
			}
		}
	}
	if !found {
		t.Fatal("created agent missing from list")
	}
}
